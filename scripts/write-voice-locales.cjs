const ph = (s) => [...String(s).matchAll(/\{\{(\w+)\}\}/g)].map((m) => m[1]).sort().join(',');
const problems = [];

for (const [file, table] of Object.entries(T)) {
  const p = path.join(LOCALES, file);
  const j = JSON.parse(fs.readFileSync(p, 'utf8'));
  const missing = Object.keys(VOICE_PHRASES).filter((k) => !(k in table));
  const extra = Object.keys(table).filter((k) => !(k in VOICE_PHRASES));
  if (missing.length) problems.push(`${file} mancano ${missing.length}: ${missing.slice(0, 6).join(', ')}`);
  if (extra.length) problems.push(`${file} in più ${extra.length}: ${extra.slice(0, 6).join(', ')}`);
  for (const [k, v] of Object.entries(table)) {
    if (k in VOICE_PHRASES && ph(v) !== ph(VOICE_PHRASES[k])) {
      problems.push(`${file}.${k} placeholder: en=[${ph(VOICE_PHRASES[k])}] got=[${ph(v)}]`);
    }
  }
  const voice = {};
  for (const k of Object.keys(VOICE_PHRASES)) voice[k] = table[k] ?? VOICE_PHRASES[k];
  j.voice = voice;
  fs.writeFileSync(p, JSON.stringify(j, null, 2) + '\n');
  console.log(file, '→', Object.keys(voice).length, 'chiavi voice');
}

if (problems.length) {
  console.log('\nPROBLEMI:');
  for (const p of problems) console.log(' -', p);
  process.exit(1);
}
